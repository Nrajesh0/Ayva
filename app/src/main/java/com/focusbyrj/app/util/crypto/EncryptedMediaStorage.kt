package com.focusbyrj.app.util.crypto

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Log
import java.io.File
import java.io.FileInputStream
import java.io.InputStream
import java.io.OutputStream
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.CipherInputStream
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Authenticated encrypted disk storage for Local Media Attachments.
 *
 * Guarantees that all images, sketches, and voice memo audio recordings stored on flash storage
 * use Android Keystore AES-256-GCM. Hardware backing depends on the device.
 * This helper never writes plaintext bytes to its destination files.
 */
object EncryptedMediaStorage {

    private const val TAG = "EncryptedMediaStorage"
    private const val ANDROID_KEYSTORE = "AndroidKeyStore"
    private const val MEDIA_KEY_ALIAS = "focus_local_media_master_key"
    private const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"
    private const val GCM_TAG_LENGTH = 128
    private const val GCM_IV_LENGTH = 12
    private const val MAGIC_HEADER = "FOC_ENC_V1:"
    const val MAX_DECRYPT_BYTES_LIMIT = 50 * 1024 * 1024L // 50MB upper limit for heap ByteArray loading

    private val isUnitTestEnvironment: Boolean get() = com.focusbyrj.app.util.crypto.TestRuntimeKeys.available

    private fun getMasterKeyForEncryption(): SecretKey {
        return try {
            val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
            if (keyStore.containsAlias(MEDIA_KEY_ALIAS)) {
                val entry = keyStore.getEntry(MEDIA_KEY_ALIAS, null) as? KeyStore.SecretKeyEntry
                if (entry != null) {
                    return entry.secretKey
                }
                throw SecurityException("Media storage master key exists in AndroidKeyStore but could not be loaded as SecretKeyEntry. Refusing to overwrite key to prevent permanent data loss.")
            }

            val keyGenerator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
            val spec = KeyGenParameterSpec.Builder(
                MEDIA_KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()

            keyGenerator.init(spec)
            keyGenerator.generateKey()
        } catch (e: Exception) {
            if (e is SecurityException) throw e
            if (isUnitTestEnvironment) {
                Log.w(TAG, "AndroidKeyStore is unavailable in unit test environment; using test software key.")
                return getTestKey()
            }
            Log.e(TAG, "AndroidKeyStore is unavailable for media storage key generation. Refusing to use static software key for new writes.", e)
            throw SecurityException("Failed to generate hardware-backed media storage key in AndroidKeyStore", e)
        }
    }

    private fun getMasterKeyForDecryption(): SecretKey? {
        return try {
            val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
            if (keyStore.containsAlias(MEDIA_KEY_ALIAS)) {
                val entry = keyStore.getEntry(MEDIA_KEY_ALIAS, null) as? KeyStore.SecretKeyEntry
                entry?.secretKey
            } else null
        } catch (e: Exception) {
            Log.w(TAG, "Failed to retrieve media storage master key from AndroidKeyStore", e)
            null
        }
    }

    internal fun getTestKey(): SecretKey = TestRuntimeKeys.key("media")

    private fun readKey(): SecretKey = getMasterKeyForDecryption()
        ?: if (TestRuntimeKeys.available) getTestKey() else throw SecurityException("Media key unavailable")

    /**
     * Encrypts plaintext bytes and writes them atomically to destination file.
     * Nonce/IV is generated by the Android Keystore cipher provider.
     */
    @Synchronized
    fun writeEncryptedBytes(file: File, plaintextBytes: ByteArray) {
        com.focusbyrj.app.data.note.MediaRetirement.protect(file)
        // Ensure parent directory exists before attempting to write temp file
        file.parentFile?.mkdirs()
        val secretKey = getMasterKeyForEncryption()
        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)
        val iv = checkNotNull(cipher.iv) { "Cipher failed to generate IV for media encryption" }
        require(iv.size == GCM_IV_LENGTH)
        val encryptedBytes = cipher.doFinal(plaintextBytes)
        val atomic = androidx.core.util.AtomicFile(file)
        val output = atomic.startWrite()
        try {
            output.write(MAGIC_HEADER.toByteArray(Charsets.UTF_8))
            output.write(iv)
            output.write(encryptedBytes)
            output.fd.sync()
            atomic.finishWrite(output)
            check(file.isFile && file.length() == MAGIC_HEADER.toByteArray().size + iv.size + encryptedBytes.size.toLong()) {
                "Encrypted media installation failed"
            }
            val expected = java.security.MessageDigest.getInstance("SHA-256").apply {
                update(MAGIC_HEADER.toByteArray(Charsets.UTF_8)); update(iv); update(encryptedBytes)
            }.digest()
            val actual = java.security.MessageDigest.getInstance("SHA-256")
            file.inputStream().use { input ->
                val buffer = ByteArray(32 * 1024)
                while (true) { val count = input.read(buffer); if (count < 0) break; actual.update(buffer, 0, count) }
            }
            check(expected.contentEquals(actual.digest())) { "Encrypted media verification failed" }
        } catch (error: Throwable) {
            atomic.failWrite(output)
            throw error
        }
    }

    /** No plaintext or static-key compatibility is accepted. Authenticate before exposing bytes. */
    fun readDecryptedBytes(file: File): ByteArray? {
        if (!file.exists() || file.length() > MAX_DECRYPT_BYTES_LIMIT) return null
        return openDecryptedInputStream(file)?.use { it.readBytes() }
    }

    fun openDecryptedInputStream(file: File): InputStream? {
        if (!file.isFile) return null
        var input: FileInputStream? = null
        return try {
            val source = FileInputStream(file); input = source
            val magic = MAGIC_HEADER.toByteArray(Charsets.UTF_8)
            val header = ByteArray(magic.size); val iv = ByteArray(GCM_IV_LENGTH)
            java.io.DataInputStream(source).apply { readFully(header); readFully(iv) }
            require(header.contentEquals(magic)) { "Unsupported media format; file retained" }
            val key = readKey()
            fun decryptor() = Cipher.getInstance(AES_GCM_TRANSFORMATION).apply {
                init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(GCM_TAG_LENGTH, iv))
            }
            // Validate the complete GCM tag before handing any plaintext to a decoder,
            // exporter or player. Reuse the same descriptor so atomic replacement cannot
            // swap the authenticated file between verification and consumption.
            val verifier = decryptor()
            val buffer = ByteArray(32 * 1024)
            while (true) {
                val n = source.read(buffer); if (n < 0) break
                verifier.update(buffer, 0, n)?.fill(0)
            }
            verifier.doFinal()?.fill(0)
            source.channel.position((magic.size + GCM_IV_LENGTH).toLong())
            CipherInputStream(source, decryptor())
        } catch (_: Exception) {
            input?.close()
            Log.e(TAG, "Media could not be authenticated; original file retained")
            null
        }
    }

    /** Atomically install only a successfully completed authenticated stream. */
    fun openEncryptedOutputStream(file: File): OutputStream {
        com.focusbyrj.app.data.note.MediaRetirement.protect(file)
        file.parentFile?.mkdirs()
        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION).apply { init(Cipher.ENCRYPT_MODE, getMasterKeyForEncryption()) }
        val iv = checkNotNull(cipher.iv); require(iv.size == GCM_IV_LENGTH)
        val atomic = androidx.core.util.AtomicFile(file)
        val output = atomic.startWrite()
        try { output.write(MAGIC_HEADER.toByteArray(Charsets.UTF_8)); output.write(iv) }
        catch (error: Throwable) { atomic.failWrite(output); throw error }
        return object : OutputStream() {
            private var closed = false
            private var failed = false
            override fun write(value: Int) = write(byteArrayOf(value.toByte()), 0, 1)
            override fun write(bytes: ByteArray, offset: Int, length: Int) {
                check(!closed) { "Media stream is closed" }
                try { cipher.update(bytes, offset, length)?.let(output::write) }
                catch (error: Throwable) { failed = true; throw error }
            }
            override fun flush() { check(!closed); try { output.flush() } catch (error: Throwable) { failed = true; throw error } }
            override fun close() {
                if (closed) return
                closed = true
                if (failed) { atomic.failWrite(output); return }
                try {
                    output.write(cipher.doFinal()); output.fd.sync(); atomic.finishWrite(output)
                } catch (error: Throwable) { atomic.failWrite(output); throw error }
            }
        }
    }

    /**
     * Checks whether the file is encrypted with the storage header.
     */
    fun isEncrypted(file: File): Boolean {
        val magicBytes = MAGIC_HEADER.toByteArray(Charsets.UTF_8)
        if (!file.exists() || file.length() < magicBytes.size) return false
        return try {
            FileInputStream(file).use { fis ->
                val header = ByteArray(magicBytes.size)
                var bytesRead = 0
                while (bytesRead < magicBytes.size) {
                    val r = fis.read(header, bytesRead, magicBytes.size - bytesRead)
                    if (r == -1) break
                    bytesRead += r
                }
                bytesRead == magicBytes.size && header.contentEquals(magicBytes)
            }
        } catch (_: Exception) {
            false
        }
    }
}
